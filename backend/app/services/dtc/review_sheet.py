"""The readable review sheet of the pre-generated explanations, for Wisdom (step 4)."""

from pathlib import Path

from app.services.dtc import definitions as dd
from app.services.dtc import pregenerated as pg

SEVERITY = {
    "info": "Info",
    "watch": "Watch",
    "service_soon": "Service soon",
    "stop_safely": "STOP SAFELY",
}

INTRO = """\
# Review: pre-generated fault-code explanations (v1)

Generated by `scripts/pregenerate_dtc.py` with {model}, prompt `{prompt}`, for a typical
petrol car (no vehicle data). Source of truth: `backend/app/config/dtc/explanations.v1.yaml`.

**How to review.** For each code, read the stored and the pending versions. Check that:
- the facts are right, and nothing is invented;
- the tone fits the severity (no more and no less urgent);
- an owner who isn't a mechanic would understand it.

Then either tell Claude the corrections (e.g. "P0171 stored: drop cause 3"), or edit the
YAML yourself and set `reviewed: true`. Only reviewed entries are shown to owners.

Status: **{reviewed} of {total} reviewed**.{problems}
"""


def _entry_md(e: dict) -> list[str]:
    x = e["explanation"]
    mark = "reviewed" if e.get("reviewed") else "**not reviewed**"
    out = [f"#### {e['status'].capitalize()} ({mark}, confidence {x['confidence']})", ""]
    out += [x["summary"], "", "Likely causes:"]
    out += [f"{i}. **{c['cause']}**: {c['why']}" for i, c in enumerate(x["likely_causes"], 1)]
    out += ["", f"What to do now: {x['what_to_do_now']}", "", "Ask the mechanic:"]
    out += [f"- {q}" for q in x["questions_for_mechanic"]]
    return [*out, ""]


def render(path: Path = pg.FILE) -> str:
    entries = pg.read(path)
    by_code: dict[str, list[dict]] = {}
    for e in entries:
        by_code.setdefault(e["code"], []).append(e)
    bad = {(e["code"], e["status"]): p for e in entries if (p := pg.check(e))}
    problems = ""
    if bad:
        problems = "\n\n**Entries that can't be served yet:**\n" + "\n".join(
            f"- {c} {s}: {'; '.join(p)}" for (c, s), p in sorted(bad.items())
        )
    first = entries[0] if entries else {}
    lines = [
        INTRO.format(
            model=first.get("model", "?"), prompt=first.get("prompt_version", "?"),
            reviewed=sum(1 for e in entries if e.get("reviewed")), total=len(entries),
            problems=problems,
        )
    ]  # fmt: skip
    for code in dd.top50():
        d = dd.get(code)
        lines += [f"## {code}: {d.desc}", ""]
        lines += [f"Severity (our rule): **{SEVERITY[d.severity]}** | system: {d.system}", ""]
        group = sorted(by_code.get(code, []), key=lambda e: pg.STATUSES.index(e["status"]))
        if not group:
            lines += ["_Not generated yet._", ""]
        for e in group:
            lines += _entry_md(e)
    return "\n".join(lines).rstrip() + "\n"


def write_sheet(out: Path, path: Path = pg.FILE) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(path), encoding="utf-8")
